-- =====================================================================================
--  PRIMEFiscal: criação do banco de dados (PostgreSQL 12 ou mais recente)
-- =====================================================================================
--
--  Como usar no deploy:
--    1. Crie um banco PostgreSQL no serviço de nuvem (Neon, Supabase, Render, Railway...).
--    2. Rode este script uma vez, pelo editor SQL do serviço ou pelo psql:
--         psql "postgresql://usuario:senha@servidor:5432/banco?sslmode=require" -f banco/criar_banco.sql
--    3. Informe a mesma URL ao backend, na variável de ambiente DATABASE_URL.
--
--  O script pode ser rodado de novo sem perder dados: ele só cria o que ainda não existe.
--  As mesmas tabelas estão descritas em backend/app/db.py, e o backend as cria sozinho
--  se não existirem; o script serve para preparar o banco antes do deploy e documentar o modelo.
--
--  Modelo:
--    notas_fiscais     área de trabalho: fila de processamento e resultado de cada extração
--    notas_salvas      banco de notas: notas conferidas e salvas pelo usuário (com o JSON extraído)
--    participantes     emitentes e destinatários, um registro por CNPJ ou CPF
--    itens_nota        produtos ou serviços de cada nota salva
--    pagamentos_nota   formas de pagamento de cada nota salva
--
--    notas_fiscais 1 ── 0..1 notas_salvas N ── 1 participantes (emitente e destinatário)
--                                  │
--                                  ├── 1 ── N itens_nota
--                                  └── 1 ── N pagamentos_nota
-- =====================================================================================

BEGIN;

-- -------------------------------------------------------------------------------------
--  Área de trabalho
-- -------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS notas_fiscais (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arquivo         VARCHAR(255) NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    lote_id         VARCHAR(36),
    abordagem       VARCHAR(10),
    tipo_documento  VARCHAR(20),
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    enfileirado_em  TIMESTAMPTZ,
    iniciado_em     TIMESTAMPTZ,
    dados           JSONB,
    validacao       JSONB,
    metadados       JSONB,
    erro            TEXT
);

CREATE INDEX IF NOT EXISTS ix_notas_fiscais_status  ON notas_fiscais (status);
CREATE INDEX IF NOT EXISTS ix_notas_fiscais_lote_id ON notas_fiscais (lote_id);

COMMENT ON TABLE  notas_fiscais           IS 'Área de trabalho: notas enviadas, fila de processamento e resultado de cada extração com IA';
COMMENT ON COLUMN notas_fiscais.status    IS 'pendente, processando, processada, revisar, revisada ou erro';
COMMENT ON COLUMN notas_fiscais.lote_id   IS 'Identifica as notas enviadas na mesma requisição';
COMMENT ON COLUMN notas_fiscais.abordagem IS 'pdf (leitura visual) ou texto (texto extraído do PDF)';
COMMENT ON COLUMN notas_fiscais.dados     IS 'JSON extraído pela IA (ou corrigido pelo usuário)';

-- -------------------------------------------------------------------------------------
--  Banco de notas
-- -------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS participantes (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj                 VARCHAR(14) UNIQUE,
    cpf                  VARCHAR(11) UNIQUE,
    razao_social         VARCHAR(255),
    inscricao_estadual   VARCHAR(20),
    inscricao_municipal  VARCHAR(20),
    endereco             VARCHAR(255),
    cep                  VARCHAR(8),
    municipio            VARCHAR(100),
    uf                   VARCHAR(2),
    criado_em            TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em        TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  participantes      IS 'Emitentes e destinatários das notas salvas; o mesmo CNPJ ou CPF é cadastrado uma vez só';
COMMENT ON COLUMN participantes.cnpj IS 'Sem pontuação; pode ter letras (CNPJ alfanumérico, a partir de 2026)';
COMMENT ON COLUMN participantes.cpf  IS 'Sem pontuação';


CREATE TABLE IF NOT EXISTS notas_salvas (
    id                          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processamento_id            INTEGER UNIQUE REFERENCES notas_fiscais (id) ON DELETE SET NULL,
    tipo_documento              VARCHAR(20) NOT NULL,
    chave_acesso                VARCHAR(44) UNIQUE,
    numero                      VARCHAR(20),
    serie                       VARCHAR(20),
    data_emissao                DATE,
    emitente_id                 INTEGER REFERENCES participantes (id),
    destinatario_id             INTEGER REFERENCES participantes (id),

    valor_total_produtos        NUMERIC(15, 2),
    valor_desconto              NUMERIC(15, 2),
    valor_frete                 NUMERIC(15, 2),
    valor_total_nota            NUMERIC(15, 2),

    base_calculo_icms           NUMERIC(15, 2),
    valor_icms                  NUMERIC(15, 2),
    valor_icms_st               NUMERIC(15, 2),
    valor_ipi                   NUMERIC(15, 2),
    valor_pis                   NUMERIC(15, 2),
    valor_cofins                NUMERIC(15, 2),
    valor_iss                   NUMERIC(15, 2),
    valor_ibs                   NUMERIC(15, 2),
    valor_cbs                   NUMERIC(15, 2),
    valor_aproximado_tributos   NUMERIC(15, 2),

    informacoes_complementares  TEXT,

    arquivo                     VARCHAR(255),
    abordagem                   VARCHAR(10),
    provedor_ia                 VARCHAR(100),
    modelo_ia                   VARCHAR(100),
    validacao_valida            BOOLEAN,
    validacao_pontuacao         DOUBLE PRECISION,

    dados                       JSONB NOT NULL,
    validacao                   JSONB,

    salva_em                    TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizada_em               TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_notas_salvas_tipo_documento
        CHECK (tipo_documento IN ('NF-e', 'NFC-e', 'NFS-e', 'desconhecido'))
);

CREATE INDEX IF NOT EXISTS ix_notas_salvas_data_emissao    ON notas_salvas (data_emissao);
CREATE INDEX IF NOT EXISTS ix_notas_salvas_emitente_id     ON notas_salvas (emitente_id);
CREATE INDEX IF NOT EXISTS ix_notas_salvas_destinatario_id ON notas_salvas (destinatario_id);

COMMENT ON TABLE  notas_salvas                     IS 'Banco de notas: notas conferidas e salvas pelo usuário';
COMMENT ON COLUMN notas_salvas.processamento_id    IS 'Nota da área de trabalho que deu origem a esta; fica nula se ela for excluída de lá';
COMMENT ON COLUMN notas_salvas.chave_acesso        IS 'Chave de 44 dígitos (NF-e e NFC-e); única, para a mesma nota não entrar duas vezes';
COMMENT ON COLUMN notas_salvas.dados               IS 'O JSON extraído, completo, como estava quando a nota foi salva';
COMMENT ON COLUMN notas_salvas.validacao           IS 'Resultado da validação fiscal (dígitos verificadores, somas)';
COMMENT ON COLUMN notas_salvas.validacao_pontuacao IS 'Fração das verificações fiscais que passaram (0 a 1)';
COMMENT ON COLUMN notas_salvas.abordagem           IS 'pdf (leitura visual) ou texto (texto extraído do PDF)';


CREATE TABLE IF NOT EXISTS itens_nota (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_id         INTEGER NOT NULL REFERENCES notas_salvas (id) ON DELETE CASCADE,
    numero_item     SMALLINT NOT NULL,
    codigo          VARCHAR(60),
    descricao       TEXT NOT NULL,
    ncm             VARCHAR(8),
    cfop            VARCHAR(4),
    unidade         VARCHAR(20),
    quantidade      NUMERIC(15, 4),
    valor_unitario  NUMERIC(21, 10),
    valor_total     NUMERIC(15, 2),
    CONSTRAINT uq_itens_nota_numero UNIQUE (nota_id, numero_item)
);

COMMENT ON TABLE  itens_nota             IS 'Produtos ou serviços de cada nota salva';
COMMENT ON COLUMN itens_nota.numero_item IS 'Posição do item na nota (1, 2, 3...)';


CREATE TABLE IF NOT EXISTS pagamentos_nota (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_id  INTEGER NOT NULL REFERENCES notas_salvas (id) ON DELETE CASCADE,
    forma    VARCHAR(60) NOT NULL,
    valor    NUMERIC(15, 2)
);

CREATE INDEX IF NOT EXISTS ix_pagamentos_nota_nota_id ON pagamentos_nota (nota_id);

COMMENT ON TABLE pagamentos_nota IS 'Formas de pagamento de cada nota salva';

-- -------------------------------------------------------------------------------------
--  Segurança (LGPD)
-- -------------------------------------------------------------------------------------
--  As notas têm CPF, nomes e endereços. Alguns serviços (ex.: Supabase) publicam as tabelas
--  do schema public numa API REST automática. Com a RLS (Row Level Security) ligada e nenhuma
--  política criada, essa API não lê nem grava nada. O backend continua com acesso total desde que
--  se conecte com o mesmo usuário que rodou este script (o dono das tabelas), que é o normal.

ALTER TABLE notas_fiscais   ENABLE ROW LEVEL SECURITY;
ALTER TABLE participantes   ENABLE ROW LEVEL SECURITY;
ALTER TABLE notas_salvas    ENABLE ROW LEVEL SECURITY;
ALTER TABLE itens_nota      ENABLE ROW LEVEL SECURITY;
ALTER TABLE pagamentos_nota ENABLE ROW LEVEL SECURITY;

COMMIT;
